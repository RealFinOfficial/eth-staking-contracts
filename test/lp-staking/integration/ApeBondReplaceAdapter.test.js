function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/** `git status --porcelain` in the repository this suite runs from, as a set of lines. */
function gitStatus() {
  const out = execFileSync("git", ["status", "--porcelain"], {
    cwd: forkNode.REPO_ROOT,
    encoding: "utf8",
  });
  return new Set(out.split("\n").filter((line) => line.trim() !== ""));
}

/**
 * Runs `fn` while the node's clock is pushed forward, and stops pushing when it returns.
 *
 * The same harness `DeployApeBond.test.js` and `ApeBondUpgradeInPlace.test.js` use:
 * `deploy-apebond.js` waits in CHAIN time, so five seconds of chain time every 150 ms of wall
 * clock clears stack #5's 300-second `minDelay` in about nine seconds. Used for the
 * replacement ONLY — the purchase's one-hour deadline and 600-second cliff must not run at
 * thirty times wall speed while the suite is asserting on them.
 */
async function withTimePump(provider, fn) {
  let running = true;
  const pump = (async () => {
    while (running) {
      try {
        await provider.send("evm_increaseTime", [5]);
        await provider.send("evm_mine", []);
      } catch {
        /* the node is busy; the next tick makes up for it */
      }
      await sleep(150);
    }
  })();

  try {
    return await fn();
  } finally {
    running = false;
    await pump;
  }
}

/**
 * `{KEY: ""}` for every key the repository's `.env` defines, or `{}` when there is no `.env`.
 * Spread UNDER the suite's own values, so what this suite sets always wins.
 */
function dotenvShield() {
  const file = path.join(forkNode.REPO_ROOT, ".env");
  if (!fs.existsSync(file)) return {};
  return Object.fromEntries(Object.keys(dotenv.parse(fs.readFileSync(file))).map((key) => [key, ""]));
}

/** Digs the revert payload out of the several shapes ethers v6 can wrap it in. */
function revertData(error) {
  for (const candidate of [
    error?.data,
    error?.info?.error?.data,
    error?.error?.data,
    error?.error?.error?.data,
  ]) {
    if (typeof candidate === "string" && candidate.startsWith("0x") && candidate.length >= 10) {
      return candidate;
    }
    if (candidate && typeof candidate.data === "string" && candidate.data.startsWith("0x")) {
      return candidate.data;
    }
  }
  return null;
}

