/**
 * `LP_APEBOND_MODE=replace-adapter`, rehearsed end to end against a FORK OF LIVE SEPOLIA.
 *
 * ── What this is ──────────────────────────────────────────────────────────────────────
 *
 * Commit "Drop soulZapRequestId from the purchase struct" changed the adapter's signed
 * `PurchaseAuthorization` from 15 fields to 14, which changes its EIP-712 type hash. The
 * adapter live on **Sepolia test stack #5** (`0xc91e4037…`) was compiled against the old
 * struct and can never verify a 14-field signature, and the adapter is REPLACEABLE, not
 * upgradeable. So stack #5 has to run `scripts/deploy-apebond.js` in `replace-adapter` mode —
 * a mode that has never run against a live stack.
 *
 * `DeployApeBond.test.js` proves the mode on MOCKS on an empty node. This suite proves it on
 * stack #5 as it stands at the chain head: its vault proxy, its 300-second timelock, its
 * escrow holding ~9,505 tREAL of bonus funding, its old adapter with the SoulZap seat
 * allowlisted, and NFT 231913 staked by the operator. It forks Sepolia at the head,
 * impersonates the two live seats, and runs the repo's own scripts, unmodified, as child
 * processes:
 *
 *   1. `scripts/deploy-apebond.js`, LP_APEBOND_MODE=replace-adapter, with exactly the
 *      environment the live day uses: the operator as the adapter's guardian, the backend key
 *      `0x9FDf…` as the purchase signer, the SoulZap seat `0x0674…` as the one caller. A new
 *      adapter against the EXISTING escrow, the handover to the timelock, ONE batch of three,
 *      the 300-second wait in chain time, the execute, the post-checks and the record.
 *   2. a static `depositFor` against the NEW adapter, signed by a throwaway key, which must
 *      revert `InvalidSignature(throwaway, 0x9FDf…)` — the adapter answers to the production
 *      key and nothing else.
 *   3. `scripts/set-purchase-signer.js`, the guardian's one undelayed transaction, pointing the
 *      fork's adapter at that throwaway key (see "Why the purchase uses a throwaway key").
 *   4. `scripts/apebond-rehearsal.js`, deposit phase: the SoulZap seat mints a position on the
 *      REAL Uniswap Sepolia position manager, in a range around the pool's current tick, signs
 *      a 14-field authorization, approves the new adapter and calls `depositFor`.
 *   5. the cliff, pushed past with one `evm_increaseTime`, and the rehearsal's claim phase:
 *      the beneficiary is paid exactly the 495 tREAL bonus out of the escrow.
 *
 * ── Why the purchase uses a throwaway key ─────────────────────────────────────────────
 *
 * The replacement runs with the PRODUCTION signer, because that is the command the live day
 * runs and the registry record must say so. But nobody here holds `0x9FDf…`'s private key,
 * and a Hardhat node can send a transaction AS an impersonated account but cannot SIGN typed
 * data for one. So the purchase proof rotates the signer on the fork to a key generated by
 * this suite — through `set-purchase-signer.js`, the same guardian-tier call the live day
 * would use for a key rotation — and phase 2 is the evidence for the production value that
 * can be had without its key: the new adapter recovers every signature against `0x9FDf…` and
 * rejects anything else.
 *
 * ── Opt-in, and NOT a CI gate ─────────────────────────────────────────────────────────
 *
 * The suite runs only when `LP_APEBOND_DRYRUN=1` is set; otherwise its `before` calls
 * `this.skip()` and every case reports as pending, exactly as its sibling
 * `ApeBondUpgradeInPlace.test.js` does. The reason is the fork block: stack #5 was deployed
 * long after every pinned block in this repo, so this suite forks the HEAD, and a head fork is
 * not deterministic (the pool price, the balances and the escrow's funding are whatever
 * Sepolia holds when the node starts). `.github/workflows/ci.yml` never sets the flag.
 *
 * Unlike the sibling, the flag alone is enough: with no `SEPOLIA_RPC_URL` and no
 * `INFURA_API_KEY` the fork is tried against the repo's public Sepolia fallbacks
 * (`profiles.sepolia.rpc.publicCandidates` — tenderly, then publicnode), the same list CI's
 * profile-driven fork suite uses. A fork that cannot be established on ANY candidate FAILS
 * the run: the operator asked for it explicitly, and a skip would read as "nothing wrong".
 *
 *     LP_APEBOND_DRYRUN=1 npx hardhat test test/lp-staking/integration/ApeBondReplaceAdapter.test.js
 *
 * ── The operator's `.env` does not leak into the children ────────────────────────────
 *
 * `hardhat.config.js` loads the repository's `.env` in every child, and the runner only strips
 * `LP_*` from THIS process's environment, so a live-day `.env` in the working tree (a
 * `LP_APEBOND_PURCHASE_SIGNER`, a `LP_REHEARSAL_CALLER_KEY`, an `LP_APEBOND_MODE`) would reach
 * the scripts and change what they do — `set-purchase-signer.js` would refuse a key that does
 * not match the address, the rehearsal would refuse a caller named twice. dotenv never
 * overrides a variable that is already present, so {@link dotenvShield} hands every child an
 * EMPTY value for each key the file defines, unless this suite sets that key itself, and every
 * script here reads an empty value as unset. The file is parsed in memory; no value is printed.
 *
 * ── Nothing in the repository is written ──────────────────────────────────────────────
 *
 * Every child records into `DEPLOYMENTS_FILE`, a scratch copy of the tracked registry with
 * the live stack's entry ALSO recorded under chain 31337, which is what the fork reports. The
 * tracked `deployments.json` and the committed `.openzeppelin/sepolia.json` are compared by
 * sha256 before and after, and `git status --porcelain` must gain no entry over the run.
 */

